-- LaTeX keymaps on <leader>l (VimTeX's own \l... localleader maps still work)
local function map(lhs, rhs, desc)
  vim.keymap.set("n", lhs, rhs, { buffer = true, desc = "LaTeX " .. desc })
end

map("<leader>ll", "<cmd>VimtexCompile<CR>", "toggle continuous compile")
map("<leader>lv", "<cmd>VimtexView<CR>", "view PDF (forward search)")
map("<leader>lt", "<cmd>VimtexTocToggle<CR>", "toggle table of contents")
map("<leader>le", "<cmd>VimtexErrors<CR>", "show compile errors")
map("<leader>lk", "<cmd>VimtexStop<CR>", "stop compiler")
map("<leader>lx", "<cmd>VimtexClean<CR>", "clean aux files")
map("<leader>lw", "<cmd>VimtexCountWords<CR>", "word count")
map("<leader>lo", "<cmd>VimtexCompileOutput<CR>", "compiler output")
map("<leader>lb", "<cmd>Telescope bibtex<CR>", "insert citation")
map("<leader>lp", function()
  require("nabla").popup()
end, "preview equation under cursor")
map("<leader>lP", function()
  require("nabla").toggle_virt()
end, "toggle inline equation previews")
